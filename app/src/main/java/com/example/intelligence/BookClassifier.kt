    fun classifyText(text: String): String {
        if (text.isBlank()) return "عام ومراجع متنوعة"

        val normalized = ArabicTextCleaner.normalizeForSearch(text)
        var bestCategory = "عام ومراجع متنوعة"
        var maxMatches = 0

        for ((category, keywords) in CATEGORY_KEYWORDS) {
            var matches = 0
            for (kw in keywords) {
                val normKw = ArabicTextCleaner.normalizeForSearch(kw)
                if (normalized.contains(normKw)) {
                    matches++
                }
            }
            if (matches > maxMatches && matches >= 3) {
                maxMatches = matches
                bestCategory = category
            }
        }

        return bestCategory
    }

    fun suggestTags(title: String, text: String, category: String): List<String> {
        val tags = mutableSetOf<String>()
        tags.add(category)

        val normalized = ArabicTextCleaner.normalizeForSearch(text)

        val potentialKeywords = listOf(
            "مخطوطات", "تراث", "دراسة نقدية", "تحقيق علمي", "وثائق",
            "فهرس", "أبحاث", "مؤتمر", "أطلس", "رسالة جامعية",
            "أدب عربي", "تاريخ إسلامي", "فقه مقارن", "شعر قديم", "شعر حديث"
        )

        for (kw in potentialKeywords) {
            val normKw = ArabicTextCleaner.normalizeForSearch(kw)
            if (normalized.contains(normKw)) {
                tags.add(kw)
            }
        }

        return tags.take(5).toList()
    }
